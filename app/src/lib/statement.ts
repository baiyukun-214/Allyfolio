import { get, all } from '../db.ts';
/** Draft accessibility statement (structure follows the EU model statement). Written as a draft for the site owner to review. */
export function draftStatement(siteId: string, orgName: string): string {
  const site = get<any>('SELECT * FROM sites WHERE id = ?', siteId);
  const scan = get<any>("SELECT * FROM scans WHERE site_id = ? AND status = 'done' ORDER BY finished_at DESC LIMIT 1", siteId);
  const top = scan ? all<any>('SELECT help, wcag, COUNT(*) AS n FROM scan_issues WHERE scan_id = ? AND impact IN (\'critical\',\'serious\') GROUP BY rule_id ORDER BY n DESC LIMIT 8', scan.id) : [];
  const date = (iso: string) => new Date(iso).toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' });
  const host = new URL(site.origin).hostname;
  return `# Accessibility statement for ${host}

> DRAFT generated by Allyfolio on ${date(new Date().toISOString())}. Review and edit every section before publishing. This draft is not legal advice.

${orgName} wants ${host} to be usable by as many people as possible. We aim to meet the Web Content Accessibility Guidelines (WCAG) 2.2 at level AA, the technical benchmark used with the European Accessibility Act (EAA) and the German BFSG via EN 301 549.

## Conformance status

[Choose one after your manual review: "fully conforms", "partially conforms" or "does not conform".] ${host} **partially conforms** to WCAG 2.2 level AA. The known issues are listed below.

## Known issues
${scan ? (top.length ? top.map((t) => `- ${t.help}${t.wcag ? ` (${t.wcag})` : ''} – found on ${t.n} element(s)`).join('\n') : '- Our automated checks did not find serious issues in the latest scan. Manual review results: [add].') : '- [No scan yet. Run a scan first.]'}
- [Add issues found in manual review, e.g. keyboard traps, unclear link text, captions.]

We are working to fix these issues. [Add planned dates if you have them.]

## How we tested

- Automated checks with axe-core in a real browser, run on a schedule${scan ? ` (latest scan: ${date(scan.finished_at)}, ${scan.pages_scanned} pages)` : ''}. Automated testing finds roughly 57% of issues (Deque study).
- Manual review: [describe – e.g. keyboard-only navigation, screen readers used, zoom to 200%].
- We do not use an accessibility overlay widget.

This statement was prepared on [date] and last reviewed on [date].

## Feedback and contact

If you find a barrier on ${host}, please contact us: [email address], [phone]. We aim to reply within [5] working days.

## Enforcement procedure

[Name the market surveillance authority for your country. In Germany: the Marktüberwachungsstelle der Länder für die Barrierefreiheit von Produkten und Dienstleistungen (MLBF). Check the current contact details.]
`;
}
